// FEFW NRO bootstrap — PLT redirect and mid hook stubs, linked into the subsdk9 module (see tools/nro_bootstrap.py).
//
// main uses LAZY binding: until a PLT entry is first called its GOT slot points at main's PLT0 resolver,
// which expects x16 = &GOT slot / x17 = *GOT slot. So the fallback never jumps to the GOT value directly;
// it runs fefw_boot_orig_N, an exact copy of the original PLT entry.
//
//   PLT entry N (patched)  ->  fefw_boot_stub_N: x9 = N, x10 = &fefw_boot_orig_N, -> dispatch
//   dispatch: target = fefw_boot_resolve(N, x1); target ? br target (our NRO hook) : br x10 (original PLT)
    .section .text.boot_stubs, "ax", %progbits

// Exported marker: identifies a subsdk9 built by tools/nro_bootstrap.py.
    .global fefw_boot_module
    .type   fefw_boot_module, %function
fefw_boot_module:
    ret

    .macro STUB idx
    .global fefw_boot_stub_\idx
fefw_boot_stub_\idx:
    mov     x9, #\idx
    adr     x10, fefw_boot_orig_\idx
    b       fefw_boot_dispatch
    .endm

    .macro ORIG idx
    .global fefw_boot_orig_\idx
    .type   fefw_boot_orig_\idx, %function
fefw_boot_orig_\idx:
    adrp    x16, fefw_got_\idx
    ldr     x17, [x16, :lo12:fefw_got_\idx]
    add     x16, x16, :lo12:fefw_got_\idx
    br      x17
    .endm

// Mid-function hook: main's instruction at the hook site was replaced by `b fefw_boot_mid_N`.
// Saves x0..x30 as a context array, calls the NRO hook `hook(ctx)` if it is loaded (index `hook` in
// fefw_boot_resolve), reloads x0..x30 from the context (the hook may change them), then executes the
// displaced instruction (`insn`, PC-independent, checked by nro_bootstrap.py) and resumes at site+4.
// NZCV is not preserved: hook sites must not have live condition flags.
    .macro MID idx, hook, insn
    .global fefw_boot_mid_\idx
fefw_boot_mid_\idx:
    sub     sp, sp, #0x100
    stp     x0, x1, [sp, #0x00]
    str     x30, [sp, #0xf0]
    mov     x0, #\hook
    bl      fefw_boot_mid_common
    ldr     x30, [sp, #0xf0]
    add     sp, sp, #0x100
    .word   \insn
    b       fefw_mid_ret_\idx
    .endm

// Shared body of the MID stubs: the stub has reserved ctx (0x100 bytes) at sp and stored x0, x1, x30 in it;
// x0 = hook index. Fast-paths cached targets directly from fefw_hook_cache without calling fefw_boot_resolve
// (or nn::ro::LookupSymbol), and skips saving x2..x29 entirely before the NRO is loaded or for missing slots.
fefw_boot_mid_common:
    adrp    x1, fefw_hook_cache
    add     x1, x1, :lo12:fefw_hook_cache
    add     x1, x1, x0, lsl #3
    ldar    x1, [x1]
    cmp     x1, #1
    b.hi    2f                    // > 1: cached NRO hook address in x1
    b.eq    4f                    // == 1: resolved missing -> fast return
    adrp    x1, fefw_nro_loaded
    add     x1, x1, :lo12:fefw_nro_loaded
    ldar    w1, [x1]
    cbnz    w1, 3f                // NRO loaded, slot not cached yet -> resolve once
4:  ldp     x0, x1, [sp, #0x00]
    ret

2:  stp     x2, x3, [sp, #0x10]
    stp     x4, x5, [sp, #0x20]
    stp     x6, x7, [sp, #0x30]
    stp     x8, x9, [sp, #0x40]
    stp     x10, x11, [sp, #0x50]
    stp     x12, x13, [sp, #0x60]
    stp     x14, x15, [sp, #0x70]
    stp     x16, x17, [sp, #0x80]
    stp     x18, x19, [sp, #0x90]
    stp     x20, x21, [sp, #0xa0]
    stp     x22, x23, [sp, #0xb0]
    stp     x24, x25, [sp, #0xc0]
    stp     x26, x27, [sp, #0xd0]
    stp     x28, x29, [sp, #0xe0]
    str     x30, [sp, #0xf8]
    mov     x16, x1
    mov     x0, sp
    blr     x16
    b       1f

3:  stp     x2, x3, [sp, #0x10]
    stp     x4, x5, [sp, #0x20]
    stp     x6, x7, [sp, #0x30]
    stp     x8, x9, [sp, #0x40]
    stp     x10, x11, [sp, #0x50]
    stp     x12, x13, [sp, #0x60]
    stp     x14, x15, [sp, #0x70]
    stp     x16, x17, [sp, #0x80]
    stp     x18, x19, [sp, #0x90]
    stp     x20, x21, [sp, #0xa0]
    stp     x22, x23, [sp, #0xb0]
    stp     x24, x25, [sp, #0xc0]
    stp     x26, x27, [sp, #0xd0]
    stp     x28, x29, [sp, #0xe0]
    str     x30, [sp, #0xf8]
    mov     x1, xzr
    bl      fefw_boot_resolve
    cbz     x0, 1f
    mov     x16, x0
    mov     x0, sp
    blr     x16
1:  ldr     x30, [sp, #0xf8]
    ldp     x0, x1, [sp, #0x00]
    ldp     x2, x3, [sp, #0x10]
    ldp     x4, x5, [sp, #0x20]
    ldp     x6, x7, [sp, #0x30]
    ldp     x8, x9, [sp, #0x40]
    ldp     x10, x11, [sp, #0x50]
    ldp     x12, x13, [sp, #0x60]
    ldp     x14, x15, [sp, #0x70]
    ldp     x16, x17, [sp, #0x80]
    ldp     x18, x19, [sp, #0x90]
    ldp     x20, x21, [sp, #0xa0]
    ldp     x22, x23, [sp, #0xb0]
    ldp     x24, x25, [sp, #0xc0]
    ldp     x26, x27, [sp, #0xd0]
    ldp     x28, x29, [sp, #0xe0]
    ret

// Generated by tools/nro_bootstrap.py: STUB/ORIG for every PLT hook, MID for every mid-function hook.
#include "boot_hooks.inc"

fefw_boot_dispatch:
    adrp    x16, fefw_hook_cache
    add     x16, x16, :lo12:fefw_hook_cache
    add     x16, x16, x9, lsl #3
    ldar    x16, [x16]
    cmp     x16, #1
    b.eq    1f                    // 1: resolved missing -> original PLT
    cbz     x16, 2f               // 0: unresolved -> slow path
    br      x16                   // cached NRO hook (zero spills, zero LookupSymbol)
2:  stp     x29, x30, [sp, #-0x60]!
    mov     x29, sp
    stp     x0, x1, [sp, #0x10]
    stp     x2, x3, [sp, #0x20]
    stp     x4, x5, [sp, #0x30]
    stp     x6, x7, [sp, #0x40]
    stp     x8, x10, [sp, #0x50]
    mov     x0, x9                // x1 still holds the caller's x1 (the path, for OpenFile)
    bl      fefw_boot_resolve
    mov     x16, x0
    ldp     x8, x10, [sp, #0x50]
    ldp     x6, x7, [sp, #0x40]
    ldp     x4, x5, [sp, #0x30]
    ldp     x2, x3, [sp, #0x20]
    ldp     x0, x1, [sp, #0x10]
    ldp     x29, x30, [sp], #0x60
    cbz     x16, 1f
    br      x16                   // NRO hook
1:  br      x10                   // original PLT entry (handles lazy binding)
