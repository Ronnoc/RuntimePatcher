// Horizon's rtld resolves main's imports by searching the loaded modules in order
// (main, subsdk0..9, sdk). Because this module defines the same mangled nn::fs symbols that
// main imports from sdk, main's file I/O lands here first. The real sdk implementations are
// looked up by name in the other modules' dynamic symbol tables.
//
// On the first open inside the RomFS mount that contains GameData/Job.bin, the foundation's
// VFS overlay engine runs once: it discovers class mods under <mount>:/GameData/Classes
// (layered in by the emulator from each mod's romfs/), synthesizes the patched tables / msbt /
// icon archives in memory, and from then on reads of those files are served from memory.
//
// Memory: the boot pass only *plans* (which files are patched, with every mod resource already read). A
// patched file is built the first time the game opens it, shared by overlapping handles, and kept in a
// bounded LRU cache after the last handle closes so re-opens avoid rebuilding while keeping RAM capped.
