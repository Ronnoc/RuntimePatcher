// Constructed lazily (no reliance on module init_array).
fefw_foundation::VfsOverlayPlan* g_plan = nullptr;  // targets + collected patches (no file bytes)
std::string* g_overlay_mount = nullptr;                          // "Contents"
volatile int g_overlay_state = 0;  // 0 = not built, 1 = building, 2 = ready (possibly empty)
volatile int g_overlay_lock = 0;
std::vector<std::string>* g_rejected_mounts = nullptr;

// One built file, shared by every open handle on it; retained in a bounded LRU cache when refs == 0.
constexpr size_t kSynthCacheMaxBytes = 16 * 1024 * 1024;      // 16 MiB idle cache budget
constexpr size_t kSynthCacheMaxFileBytes = 8 * 1024 * 1024;   // do not cache single files > 8 MiB after close

struct SynthFile {
    std::string vpath;
    std::vector<uint8_t> data;
    int refs = 0;
    uint64_t last_used = 0;
};
std::map<std::string, SynthFile*>* g_live = nullptr;  // vpath -> built file (open or idle cached)
volatile int g_live_lock = 0;
size_t g_live_bytes = 0;
size_t g_cached_bytes = 0;  // subset of g_live_bytes with refs == 0
uint64_t g_lru_clock = 0;
int g_build_count = 0;
int g_cache_hits = 0;

// Immutable fast lookup table for g_plan->target_paths (populated once in build_overlay).
uint64_t g_target_bloom[4] = {};
std::vector<const char*>* g_target_cstrs = nullptr;

uint64_t fnv1a_cstr(const char* s) {
    uint64_t h = 14695981039346656037ULL;
    for (; *s; ++s) {
        h ^= static_cast<uint8_t>(*s);
        h *= 1099511628211ULL;
    }
    return h;
}

struct OpenSynth {
    void* handle;
    SynthFile* data;
};
constexpr int kMaxOpenSynth = 64;
OpenSynth g_open[kMaxOpenSynth];
volatile int g_open_lock = 0;
volatile int g_open_count = 0;

const std::vector<uint8_t>* find_open(FileHandle h) {
    if (__atomic_load_n(&g_open_count, __ATOMIC_ACQUIRE) == 0) return nullptr;
    const std::vector<uint8_t>* r = nullptr;
    spin_lock(&g_open_lock);
    for (auto& e : g_open) {
        if (e.data && e.handle == h.handle) {
            r = &e.data->data;
            break;
        }
    }
    spin_unlock(&g_open_lock);
    return r;
}

bool register_open(FileHandle h, SynthFile* data) {
    bool ok = false;
    spin_lock(&g_open_lock);
    for (auto& e : g_open) {
        if (!e.data) {
            e.handle = h.handle;
            e.data = data;
            __atomic_add_fetch(&g_open_count, 1, __ATOMIC_RELEASE);
            ok = true;
            break;
        }
    }
    spin_unlock(&g_open_lock);
    return ok;
}

SynthFile* unregister_open(FileHandle h) {
    if (__atomic_load_n(&g_open_count, __ATOMIC_ACQUIRE) == 0) return nullptr;
    SynthFile* found = nullptr;
    spin_lock(&g_open_lock);
    for (auto& e : g_open) {
        if (e.data && e.handle == h.handle) {
            found = e.data;
            e.data = nullptr;
            e.handle = nullptr;
            __atomic_sub_fetch(&g_open_count, 1, __ATOMIC_RELEASE);
            break;
        }
    }
    spin_unlock(&g_open_lock);
    return found;
}

// Splits "Contents:/GameData/Job.bin" into mount view "Contents" and virtual path "/GameData/Job.bin"
// without heap allocations.
bool split_mount_path_view(const char* path, const char*& mount_ptr, size_t& mount_len, const char*& vpath_ptr) {
    const char* colon = strstr(path, ":/");
    if (!colon || colon == path) return false;
    mount_ptr = path;
    mount_len = static_cast<size_t>(colon - path);
    const char* p = colon + 1;
    while (p[0] == '/' && p[1] == '/') ++p;
    vpath_ptr = p;
    return true;
}

void build_overlay(const std::string& mount) {
    fefw_nx::log("building class overlay from %s:/GameData/Classes ...", mount.c_str());
    std::string root = mount + ":";
    fefw_foundation::HostFs host_fs;
    host_fs.read_file = [](const std::string& p, std::vector<uint8_t>& out) { return real_read_whole(p, out); };
    host_fs.list_dir = [](const std::string& d, std::vector<fefw_foundation::HostDirEntry>& out) {
        return real_list_dir(d, out);
    };
    auto read_base = [&root](const std::string& vpath, std::vector<uint8_t>& out) {
        return real_read_whole(root + vpath, out);
    };

    (void)read_base;
    auto* plan = new fefw_foundation::VfsOverlayPlan();
    std::string err;
    bool ok = fefw_foundation::plan_vfs_overlays({root}, host_fs, *plan, &err);

    for (const auto& id : plan->applied_mods) fefw_nx::log("  mod: %s", id.c_str());
    if (!ok || !err.empty()) fefw_nx::log("  overlay engine reported: %s", err.empty() ? "failure" : err.c_str());

    auto* cstrs = new std::vector<const char*>();
    cstrs->reserve(plan->target_paths.size());
    for (const auto& tp : plan->target_paths) {
        cstrs->push_back(tp.c_str());
        uint64_t h = fnv1a_cstr(tp.c_str());
        g_target_bloom[(h >> 6) & 3] |= (1ULL << (h & 63));
    }

    g_plan = plan;
    g_target_cstrs = cstrs;
    g_live = new std::map<std::string, SynthFile*>();
    g_overlay_mount = new std::string(mount);
    fefw_nx::log("class overlay ready: %zu mod(s), %zu patched file(s), built on first open",
                 plan->applied_mods.size(), plan->target_paths.size());
}

// Returns the built file for `vpath` with one more reference, reusing the LRU cache or building on miss.
SynthFile* acquire_synth(const std::string& mount, const std::string& vpath) {
    spin_lock(&g_live_lock);
    SynthFile* f = nullptr;
    auto it = g_live->find(vpath);
    if (it != g_live->end()) {
        f = it->second;
        if (f->refs == 0) {
            g_cached_bytes -= f->data.size();
            ++g_cache_hits;
        }
    } else {
        std::string root = mount + ":";
        auto read_base = [&root](const std::string& vp, std::vector<uint8_t>& out) {
            return real_read_whole(root + vp, out);
        };
        auto* nf = new SynthFile();
        nf->vpath = vpath;
        std::string err;
        if (fefw_foundation::synthesize_vfs_file(*g_plan, vpath, read_base, nf->data, &err)) {
            f = nf;
            (*g_live)[vpath] = f;
            g_live_bytes += f->data.size();
            ++g_build_count;
            fefw_nx::log("built %s (%zu bytes; live %zu bytes in %zu file(s); builds %d, hits %d)", vpath.c_str(),
                         f->data.size(), g_live_bytes, g_live->size(), g_build_count, g_cache_hits);
        } else {
            fefw_nx::log("build of %s failed (%s): serving the base file", vpath.c_str(),
                         err.empty() ? "no base" : err.c_str());
            delete nf;
        }
    }
    if (f) {
        ++f->refs;
        f->last_used = ++g_lru_clock;
    }
    spin_unlock(&g_live_lock);
    return f;
}

void release_synth(SynthFile* f) {
    spin_lock(&g_live_lock);
    if (--f->refs <= 0) {
        f->refs = 0;
        if (f->data.size() > kSynthCacheMaxFileBytes) {
            g_live->erase(f->vpath);
            g_live_bytes -= f->data.size();
            fefw_nx::log("freed %s (%zu bytes; live %zu bytes)", f->vpath.c_str(), f->data.size(), g_live_bytes);
            delete f;
        } else {
            f->last_used = ++g_lru_clock;
            g_cached_bytes += f->data.size();
            while (g_cached_bytes > kSynthCacheMaxBytes) {
                auto evict = g_live->end();
                for (auto it = g_live->begin(); it != g_live->end(); ++it) {
                    if (it->second->refs == 0 &&
                        (evict == g_live->end() || it->second->last_used < evict->second->last_used)) {
                        evict = it;
                    }
                }
                if (evict == g_live->end()) break;
                SynthFile* ev = evict->second;
                g_live->erase(evict);
                g_live_bytes -= ev->data.size();
                g_cached_bytes -= ev->data.size();
                fefw_nx::log("evicted %s (%zu bytes; cached %zu bytes)", ev->vpath.c_str(), ev->data.size(),
                             g_cached_bytes);
                delete ev;
            }
        }
    }
    spin_unlock(&g_live_lock);
}

// Plugin host adapters (nn::ro wants page-aligned images that stay alive while the module is loaded).
bool plugin_read(const char* path, void** out, size_t* out_size) {
    std::vector<uint8_t> data;
    if (!real_read_whole(path, data) || data.empty()) return false;
    size_t size = (data.size() + 0xFFF) & ~size_t(0xFFF);
    auto raw = reinterpret_cast<uintptr_t>(malloc(size + 0x1000));
    if (!raw) return false;
    auto* p = reinterpret_cast<uint8_t*>((raw + 0xFFF) & ~uintptr_t(0xFFF));
    memset(p, 0, size);
    memcpy(p, data.data(), data.size());
    *out = p;
    *out_size = data.size();
    return true;
}

bool plugin_list(const char* dir, void (*on_file)(void*, const char*), void* ctx) {
    std::vector<fefw_foundation::HostDirEntry> entries;
    if (!real_list_dir(dir, entries)) return false;
    for (const auto& e : entries) {
        if (!e.is_dir) on_file(ctx, e.name.c_str());
    }
    return true;
}

// Builds the overlay the first time a file inside the game's RomFS mount is opened.
void maybe_build_overlay(const std::string& mount) {
    if (__atomic_load_n(&g_overlay_state, __ATOMIC_ACQUIRE) == 2) return;
    spin_lock(&g_overlay_lock);
    if (g_overlay_state == 0) {
        if (!g_rejected_mounts) g_rejected_mounts = new std::vector<std::string>();
        bool rejected = false;
        for (const auto& m : *g_rejected_mounts) rejected |= (m == mount);
        if (!rejected) {
            if (real_is_file(mount + ":/GameData/Job.bin")) {
                g_overlay_state = 1;
                if (!FEFW_NX_NRO && real_is_file(mount + ":/fefw_probe/probe.nro")) {
                    fefw_nx::run_nro_probe(mount, [](const std::string& p, std::vector<uint8_t>& out) {
                        return real_read_whole(p, out);
                    });
                }
                build_overlay(mount);
                __atomic_store_n(&g_overlay_state, 2, __ATOMIC_RELEASE);
                fefw_nx::load_plugins(mount.c_str(), &plugin_read, &plugin_list);
            } else {
                g_rejected_mounts->push_back(mount);
            }
        }
    }
    spin_unlock(&g_overlay_lock);
}

bool is_target_cstr(const char* mount_ptr, size_t mount_len, const char* vpath_ptr) {
    if (__atomic_load_n(&g_overlay_state, __ATOMIC_ACQUIRE) != 2 || !g_target_cstrs || g_target_cstrs->empty())
        return false;
    if (mount_len != g_overlay_mount->size() || memcmp(mount_ptr, g_overlay_mount->data(), mount_len) != 0)
        return false;
    uint64_t h = fnv1a_cstr(vpath_ptr);
    if ((g_target_bloom[(h >> 6) & 3] & (1ULL << (h & 63))) == 0) return false;
    size_t lo = 0, hi = g_target_cstrs->size();
    while (lo < hi) {
        size_t mid = lo + (hi - lo) / 2;
        int cmp = strcmp((*g_target_cstrs)[mid], vpath_ptr);
        if (cmp == 0) return true;
        if (cmp < 0)
            lo = mid + 1;
        else
            hi = mid;
    }
    return false;
}

